import Foundation
import Testing
@testable import HermesHQNative

/// [quiet] A bot that runs its builds and tests in the background wakes on each one finishing and writes you a bubble:
/// "UI gate passed, unit suite still running", "that notice is for a run I already reported". Between two of your
/// messages they stacked down the chat (owner, 2026-11-18: "sessions on HQ are including a lot of internal chatter").
/// Its replies between two finished tasks fold into the run's line with the tasks; its first answer after your message
/// and its last word before your next one keep their bubbles.
@MainActor
struct BackgroundChatterFoldTests {
    private let now = Date(timeIntervalSince1970: 1_790_000_000)

    private func at(_ minutesAgo: Double) -> Date { now.addingTimeInterval(-minutesAgo * 60) }
    private func you(_ id: String, _ text: String, _ m: Double) -> ChatMessage {
        ChatMessage(id: id, role: .user, parts: [.text(text)], timestamp: at(m), rowId: nil)
    }
    private func bot(_ id: String, _ text: String, _ m: Double) -> ChatMessage {
        ChatMessage(id: id, role: .assistant, parts: [.text(text)], timestamp: at(m), rowId: nil)
    }
    /// The gateway's note when a background process this bot started ends (as it reaches the chat: a prompt).
    private func finished(_ id: String, _ command: String, code: Int = 0, _ m: Double) -> ChatMessage {
        let how = code == 0 ? "completed normally (exit code 0)" : "exited (exit code \(code))"
        let note = "[IMPORTANT: Background process proc_\(id) \(how).\nCommand: \(command)\nOutput:\nok\n]\n\n"
            + "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
        return you(id, note, m)
    }

    private var ship: [ChatMessage] {
        [
            you("q-u1", "Ship it", 60),
            bot("q-a1", "Gating the merged tree in the background: UI tests, the full unit suite and the Mac build.", 59),
            finished("q-p1", "xcodebuild test -scheme UITests", 40),
            bot("q-a2", "UI gate passed on the merged tree. Unit suite still running.", 39.9),
            finished("q-p2", "xcodebuild test -scheme UnitTests", code: 65, 30),
            bot("q-a3", "That exit 65 is the failing-first run from this morning, before the fix existed. Nothing changes.", 29.9),
            finished("q-p3", "xcodebuild test -scheme UnitTests", 20),
            bot("q-a4", "Build 1103 is archived and uploaded; Apple shows it processed and it's in the internal group.", 19.9),
            you("q-u2", "Thanks", 5),
        ]
    }

    private func input(_ raw: [ChatMessage]) -> ChatRowBuilder.Input {
        ChatRowBuilder.Input(messages: TimelineNotes.resolve(raw), isRunning: false, botName: "App", expanded: [], scope: "t")
    }

    private func bubbles(_ rows: [ChatRow]) -> [String] { rows.filter(\.isBubble).map(\.id) }

    /// Your message, the first answer, one line for the tasks and the replies between them, the last word, your next.
    @Test func repliesBetweenFinishedTasksFold() throws {
        let rows = ChatRowBuilder.build(input(ship))
        #expect(bubbles(rows) == ["q-u1|b0", "q-a1|b0", "q-a4|b0", "q-u2|b0"], "\(rows.map(\.id))")
        let lines = rows.filter { if case .backgroundResult = $0.kind { return true } else { return false } }
        #expect(lines.count == 1, "\(lines.map(\.id))")
        let line = try #require(lines.first)
        guard case .backgroundResult(let b) = line.kind else { return }
        // Three tasks and the two replies between them.
        #expect(b.group?.count == 5)
        let at = try #require(rows.firstIndex { $0.id == line.id })
        #expect(rows[at - 1].id == "q-a1|b0" && rows[at + 1].id == "q-a4|b0")
        // The sheet holds the folded replies' words, in order.
        let members = UpdateGroups.opened(line: line.id, messageId: line.messageId, input: input(ship))?.members ?? []
        #expect(members.contains { $0.messageId == "q-a2" } && members.contains { $0.messageId == "q-a3" })
    }

    /// A task with nothing said after it, or a single reply after a single task: nothing folds that a person would miss.
    @Test func aLoneTaskAndItsReplyStay() {
        let one = [you("s-u1", "Run the tests", 30), bot("s-a1", "Running them in the background.", 29.9),
                   finished("s-p1", "xcodebuild test", 10), bot("s-a2", "All 214 tests passed.", 9.9)]
        let rows = ChatRowBuilder.build(input(one))
        #expect(bubbles(rows) == ["s-u1|b0", "s-a1|b0", "s-a2|b0"], "\(rows.map(\.id))")
    }

    /// Your message ends the stretch: the reply after it is an answer, whatever finished before it.
    @Test func yourMessageEndsTheStretch() {
        let chat = ship + [finished("q-p4", "xcodebuild archive", 4), bot("q-a5", "You're welcome.", 3.9)]
        let rows = ChatRowBuilder.build(input(chat))
        #expect(bubbles(rows).suffix(2) == ["q-u2|b0", "q-a5|b0"], "\(rows.map(\.id))")
    }

    /// A chat with no background work is unchanged: two replies in a row both stay.
    @Test func plainChatUnchanged() {
        let chat = [you("p-u1", "Hi", 3), bot("p-a1", "Hello.", 2.9), bot("p-a2", "Also, build 1102 is live.", 2.8)]
        let rows = ChatRowBuilder.build(input(chat))
        #expect(bubbles(rows) == ["p-u1|b0", "p-a1|b0", "p-a2|b0"])
    }
}
